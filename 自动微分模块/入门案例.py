"""

自动微分模块：
    对损失函数求导，结合反向传播，更新权重参数w,b

权重更新公式：
    W新 = W旧 - 学习率 * 梯度

    梯度 = 损失函数对权重参数的导数

关于损失函数的导数，无需我们手动计算，自动微分模块实现针对于不同的损失函数求导，从而实现结合反向传播，更新权重参数w,b

细节：
    只有标量张量才能求导，且大多数底层操作都是浮点型
"""

import torch

#定义权重w
#参1：初始值，参2：是否自动微分（求导），参3：数据类型
w = torch.tensor(10, requires_grad=True,dtype=torch.float)

#定义loss变量，表示损失函数
loss = 2 * w ** 2           #求导：4w

#计算梯度，梯度 = 损失函数对权重参数的导数，计算完毕后，会记录到w.grad属性中
loss.sum().backward()       #保证loss是标量张量

#代入权重更新公式：W新 = W旧 - 学习率 * 梯度
w.data = w.data - 0.01 * w.grad
print(f'更新后的权重：{w}')


