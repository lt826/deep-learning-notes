"""

分类：
    简单行列索引
    列表索引
    范围索引
    布尔索引
    多维索引

掌握：
    简单行列索引，范围索引，多维索引
"""

import torch

#设置随机种子
torch.manual_seed(23)

#创建随机张量
t1 = torch.randint(1,10,(5,5))
print(t1)
print("-"*30)

#场景1：简单行列索引，格式：张量对象[行索引，列索引]
print(t1[1])        #输出第二行
print(t1[:,2])      #输出第三列的元素
print(t1[1,2])      #输出第二行第三列的元素
print("-"*30)

#场景2：列表索引，前面的表示行，后面的表示列
print(t1[[1,2,3],[0,1,2]])      #输出第二行第一列，第三行第二列，第四行第三列的元素
print(t1[[[0],[1]],[1,2]])      #输出第0,2行第2,3列的元素
print("-"*30)

#场景3：范围索引
print(t1[:3,:2])            #输出前3行，前2列的元素
print(t1[1::2,::2])         #奇数行，偶数列
print("-"*30)

#场景4：布尔索引
print(t1[t1[:,2]>3])      #输出第三列大于3的 所有行元素
print("-"*30)

#场景5：多维索引，2个3行4列的矩阵
t1 = torch.randint(1,10,(2,3,4))
print(t1)
print("-"*30)

print(t1[0,:,:])        #获取0轴上的第一个数据
print(t1[:,0,:])        #获取1轴上的第一个数据
print(t1[:,:,0])        #获取2轴上的第一个数据
