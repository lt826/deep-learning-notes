"""

循环网络层
    基于上一次的隐藏状态 + 本次的输入 -> 本次的隐藏状态，本次的输出

    公式：
        本次的隐藏状态 = tanh(上次的隐藏状态加权求和 + 本次的输入加权求和)
        本次的输出 = 本次的隐藏状态加权求和，用词汇表中所有词的概率，选概率最大的那个词作为最终预测结果

"""

import torch
import torch.nn as nn

#1. 创建循环网络层
#参1：词向量维度，参2：隐藏状态向量维度，参3：隐藏层数
rnn = nn.RNN(input_size=128,hidden_size=256,num_layers=1)

#2. 定义变量，表示输入的x
#参1：每个句子的词的个数(长度)，参2：句子的数量，参3：词向量的维度
x= torch.randn(size=(5,32,128))

#3. 定义变量，记录上一时刻的隐藏状态
#参1：隐藏层数，参2：句子的数量，参3：隐藏状态向量的维度
h0 = torch.randn(size=(1,32,256))

#4. 调用RNN处理，获取到当前时刻的预测值和当前的隐藏状态
#output:每个时间步的输出，包含了所有时间步的隐藏状态
#h1:最后一个时间步的隐藏状态
output,h1 = rnn(x,h0)

print(f'output:{output.shape}')     # (5, 32, 256)
print(f'h1:{h1.shape}')             # (1, 32, 256)
